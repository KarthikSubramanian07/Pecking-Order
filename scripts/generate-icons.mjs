#!/usr/bin/env node
/**
 * Generates src/ui/icons.tsx from Phosphor's raw SVGs, containing ONLY the
 * icons the app imports from '@/ui/icons' (and only regular + bold weights).
 * The full Phosphor React package ships six weights per icon (~76 KB min);
 * this keeps the same look for a few KB.
 *
 *   npm run icons          regenerate after importing a new icon name
 *   npm run icons -- --check   fail if icons.tsx is out of date (CI)
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const OUT = join(ROOT, 'src/ui/icons.tsx')
const ASSETS = join(ROOT, 'node_modules/@phosphor-icons/core/assets')

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) yield* files(p)
    else if (/\.tsx?$/.test(name) && p !== OUT) yield p
  }
}

const names = new Set()
const IMPORT = /import\s*\{([^}]+)\}\s*from\s*['"](?:@\/ui\/icons|(?:\.\.?\/)+icons)['"]/g
for (const file of files(join(ROOT, 'src'))) {
  for (const m of readFileSync(file, 'utf8').matchAll(IMPORT)) {
    for (const n of m[1].split(',').map((s) => s.replace(/^type\s+/, '').trim())) {
      if (/^[A-Z]\w*$/.test(n)) names.add(n)
    }
  }
}

const kebab = (n) =>
  n
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase()

function paths(file) {
  const svg = readFileSync(file, 'utf8')
  const inner = svg.replace(/^<svg[^>]*>|<\/svg>\s*$/g, '')
  const ds = [...inner.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((m) => m[1])
  const leftover = inner.replace(/<path d="[^"]+"\s*\/>/g, '').trim()
  if (leftover) throw new Error(`${file}: unsupported SVG content: ${leftover.slice(0, 80)}`)
  return ds
}

const sorted = [...names].sort()
const defsByName = Object.fromEntries(
  sorted.map((n) => {
    const k = kebab(n)
    const regular = paths(join(ASSETS, 'regular', `${k}.svg`))
    const bold = paths(join(ASSETS, 'bold', `${k}-bold.svg`))
    return [n, `{ regular: ${JSON.stringify(regular)}, bold: ${JSON.stringify(bold)} }`]
  }),
)

const source = `// GENERATED by scripts/generate-icons.mjs from @phosphor-icons/core. Do not edit.
// Import icons from '@/ui/icons' as you would from Phosphor, then run \`npm run icons\`.
// Each icon is its own pure export, so bundles only carry the icons they use.
import type { SVGProps } from 'react'

type Weight = 'regular' | 'bold'
type Paths = Readonly<Record<Weight, readonly string[]>>

interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'ref'> {
  size?: number
  weight?: Weight
}

function make(name: string, paths: Paths) {
  function Icon({ size = 20, weight = 'regular', ...rest }: IconProps) {
    return (
      <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 256 256" fill="currentColor" {...rest}>
        {paths[weight].map((d) => (
          <path key={d} d={d} />
        ))}
      </svg>
    )
  }
  Icon.displayName = name
  return Icon
}

${sorted.map((n) => `export const ${n} = /* @__PURE__ */ make('${n}', ${defsByName[n]})`).join('\n')}
`

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== source) {
    console.error('src/ui/icons.tsx is out of date. Run `npm run icons`.')
    process.exit(1)
  }
  console.log(`icons.tsx up to date (${sorted.length} icons)`)
} else {
  writeFileSync(OUT, source)
  console.log(`Wrote ${sorted.length} icons to src/ui/icons.tsx`)
}
